#!/usr/bin/env python3
"""Assemble research/notes.md from topics/*.md, claims/*.jsonl and sources/*.jsonl.

Usage: python3 research/tools/build_notes.py
notes.md is generated: edit the topic, claim and source files, then rebuild.
"""
import importlib.util
import json
from datetime import date
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]  # research/
_spec = importlib.util.spec_from_file_location("check", Path(__file__).with_name("check.py"))
check = importlib.util.module_from_spec(_spec)
_spec.loader.exec_module(check)
MARK = {"ok": "ok", "manual": "manual", "failed": "FAILED"}
CLUSTERS = {t["prefix"]: t["title"] for t in check.TOPICS}


def rows(path):
    if not path.exists():
        return []
    return [json.loads(l) for l in path.read_text(encoding="utf-8").splitlines() if l.strip()]


def cell(v):
    return str(v).replace("|", "\\|").replace("\n", " ").strip() or "–"


def link(s):
    return f"[{'doi' if s.get('doi') else 'link'}]({'https://doi.org/' + s['doi'] if s.get('doi') else s['url']})"


def demote(md):
    return "\n".join("#" + l if l.startswith("#") else l for l in md.splitlines())


def main():
    sources = {}
    for f in sorted((ROOT / "sources").glob("*.jsonl")):
        for s in rows(f):
            sources.setdefault(s["key"], s)
    out = [
        "# Research notes: AI Coach knowledge base", "",
        f"_Generated by `research/tools/build_notes.py` on {date.today().isoformat()} from `research/topics/`, "
        "`research/claims/` and `research/sources/`. Edit those files and rebuild; do not edit this file by hand._", "",
        "## Method", "",
        "- Protocol for every research agent: [`research/PROTOCOL.md`](PROTOCOL.md).",
        "- **Evidence levels:** `consensus` (position stand, consensus statement or guideline of a professional body) · "
        "`meta-analysis` (systematic review with or without meta-analysis) · `single study` · `expert opinion` "
        "(narrative review, Delphi, textbook, practitioner). Practitioner sources are marked **[practitioner]** and are supplementary only.",
        "- **Check:** `ok` = the quote containing the number was found verbatim, by script, in the saved source text "
        "(`research/raw/`, not committed); `manual` = transcribed from a PDF, verified by hand; `FAILED` = failed the check, not usable yet.",
        "- **Contested** = credible sources disagree or the evidence is weak; see each topic's *Contested areas*.", "",
    ]
    result = check.run()
    status = result["status"]
    out += ["## Status", "", "| Cluster | Topic | Sources | Claims | ok | manual | FAILED | Contested |",
            "|---|---|---|---|---|---|---|---|"]
    all_contested, sections = [], []
    for p, name in CLUSTERS.items():
        claims = rows(ROOT / "claims" / f"{p}.jsonl")
        own = {s["key"] for s in rows(ROOT / "sources" / f"{p}.jsonl")} | {c["source"] for c in claims}
        counts = {k: sum(status.get(c["id"]) == k for c in claims) for k in MARK}
        contested = [c for c in claims if c.get("contested") is True]
        all_contested += [(p, c) for c in contested]
        out.append(f"| [{p}](#{p.lower()}) | {name} | {len(own)} | {len(claims)} | {counts['ok']} | "
                   f"{counts['manual']} | {counts['failed']} | {len(contested)} |")
        topic = ROOT / "topics" / f"{p}.md"
        if not claims and not topic.exists():
            continue
        sec = ["", f'<a id="{p.lower()}"></a>', f"## {p}: {name}", ""]
        if topic.exists():
            sec += [demote(topic.read_text(encoding="utf-8").strip()), ""]
        if claims:
            sec += [f"### {p} claims", "", "| ID | Claim | Number | Population | Source | Level | Check | Contested | Used for |",
                    "|---|---|---|---|---|---|---|---|---|"]
            for c in claims:
                s = sources.get(c["source"], {})
                src = f"{cell(s.get('authors', c['source']).split(',')[0])} {s.get('year', '')} {link(s) if s else ''}"
                sec.append(f"| {c['id']} | {cell(c['claim'])} | {cell(c.get('number', ''))} | {cell(c.get('population', ''))} | "
                           f"{src} | {cell(s.get('level', '?'))}{' [practitioner]' if s.get('practitioner') else ''} | "
                           f"{MARK.get(status.get(c['id']), '?')} | {'yes' if c.get('contested') else ''} | {cell(c['used_for'])} |")
        listed = sorted((sources[k] for k in own if k in sources), key=lambda s: (s["level"], str(s["year"]), s["key"]))
        if listed:
            sec += ["", f"### {p} sources", "", "| Key | Authors | Year | Title | Venue | Level | Link |", "|---|---|---|---|---|---|---|"]
            for s in listed:
                authors = s["authors"].split(", ")
                au = authors[0] + (" et al." if len(authors) > 2 else (", " + authors[1] if len(authors) == 2 else ""))
                sec.append(f"| {s['key']} | {cell(au)} | {s['year']} | {cell(s['title'])} | {cell(s['venue'])} | "
                           f"{s['level']}{' **[practitioner]**' if s.get('practitioner') else ''} | {link(s)} |")
        sections += sec
    out += sections
    if all_contested:
        out += ["", "## All contested claims", ""]
        out += [f"- **{c['id']}**: {c['claim']}" for _, c in all_contested]
    out += ["", "## Check output", "", "```", check.report(result, verbose=True), "```", ""]
    (ROOT / "notes.md").write_text("\n".join(out), encoding="utf-8")
    print(f"wrote research/notes.md ({len(out)} lines); {len(result['errors'])} check error(s)")


if __name__ == "__main__":
    main()
